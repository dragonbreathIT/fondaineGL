// fondaineGL glTF 2.0 — output (engine-facing) types and the raw JSON schema subset we read.
// Pure data: nothing in this module touches the GPU.

// ---------------------------------------------------------------- output types

export type GLTFTopology = 'triangle-list' | 'line-list' | 'point-list';

export interface GLTFPrimitive {
  positions: Float32Array;            // xyz
  normals?: Float32Array;             // xyz
  tangents?: Float32Array;            // xyzw
  uvs?: Float32Array;                 // TEXCOORD_0
  uvs2?: Float32Array;                // TEXCOORD_1
  colors?: Float32Array;              // COLOR_0 as rgba float
  joints?: Uint16Array;               // JOINTS_0 (4 per vertex)
  weights?: Float32Array;             // WEIGHTS_0 (4 per vertex, renormalized to sum 1)
  /** Always present (0..n-1 generated if non-indexed). Triangle list for triangle primitives (strips/fans converted). */
  indices: Uint32Array;
  material: number;                   // -1 if none
  bounds: { min: [number, number, number]; max: [number, number, number] };
  morphTargets?: { positions?: Float32Array; normals?: Float32Array; tangents?: Float32Array }[];
  /** Added: topology of `indices`. Triangle modes are converted to 'triangle-list', line strips/loops to 'line-list'. */
  topology: GLTFTopology;
  /** Added: vertex count. */
  vertexCount: number;
  /** Added: true when normals were generated (flat) because the source had none. */
  generatedNormals: boolean;
  /** Added: true when tangents were generated by `generateTangents`. */
  generatedTangents: boolean;
}

export interface GLTFMesh { name: string; primitives: GLTFPrimitive[]; weights?: number[] }

export interface GLTFSampler {
  magFilter: 'linear' | 'nearest';
  minFilter: 'linear' | 'nearest';
  mipmap: boolean;
  /** Added: filter between mip levels (meaningful when `mipmap`). */
  mipmapFilter: 'linear' | 'nearest';
  wrapS: GPUAddressMode;
  wrapT: GPUAddressMode;
}

export interface GLTFTextureTransform { offset: [number, number]; rotation: number; scale: [number, number] }

export interface GLTFTextureInfo {
  image: number;
  sampler: GLTFSampler;
  texCoord: number;
  transform?: GLTFTextureTransform;
}

export interface GLTFMaterial {
  name: string;
  baseColorFactor: [number, number, number, number]; baseColorTexture?: GLTFTextureInfo;
  metallicFactor: number; roughnessFactor: number; metallicRoughnessTexture?: GLTFTextureInfo;
  normalTexture?: GLTFTextureInfo; normalScale: number;
  occlusionTexture?: GLTFTextureInfo; occlusionStrength: number;
  emissiveTexture?: GLTFTextureInfo; emissiveFactor: [number, number, number]; emissiveStrength: number; // KHR_materials_emissive_strength
  alphaMode: 'OPAQUE' | 'MASK' | 'BLEND'; alphaCutoff: number; doubleSided: boolean; unlit: boolean;
  ior?: number; specularFactor?: number; clearcoat?: { factor: number; roughness: number };
  transmission?: number;
  // ---- added (data only)
  specularColorFactor?: [number, number, number];
  specularTexture?: GLTFTextureInfo;
  specularColorTexture?: GLTFTextureInfo;
  clearcoatTexture?: GLTFTextureInfo;
  clearcoatRoughnessTexture?: GLTFTextureInfo;
  clearcoatNormalTexture?: GLTFTextureInfo;
  transmissionTexture?: GLTFTextureInfo;
}

export interface GLTFLight {
  type: 'directional' | 'point' | 'spot';
  color: [number, number, number];
  intensity: number;
  range?: number;
  innerConeAngle?: number;
  outerConeAngle?: number;
  /** Added. */
  name?: string;
}

export interface GLTFNode {
  name: string; children: number[]; parent: number; mesh?: number; skin?: number; camera?: number;
  translation: [number, number, number]; rotation: [number, number, number, number]; scale: [number, number, number];
  light?: GLTFLight; // KHR_lights_punctual
  /** Added: morph weights override for the node's mesh. */
  weights?: number[];
}

export interface GLTFSkin {
  name: string;
  joints: number[];
  /** 16 floats per joint (column-major), identity if absent. */
  inverseBindMatrices: Float32Array;
  skeleton?: number;
}

export interface GLTFAnimationChannel { node: number; path: 'translation' | 'rotation' | 'scale' | 'weights'; sampler: number }
export interface GLTFAnimationSampler {
  input: Float32Array;
  /** For CUBICSPLINE: per keyframe [inTangent, value, outTangent], each `components` floats. */
  output: Float32Array;
  interpolation: 'LINEAR' | 'STEP' | 'CUBICSPLINE';
  /** Floats per value (3 translation/scale, 4 rotation, morph-target count for weights). */
  components: number;
}
export interface GLTFAnimation { name: string; channels: GLTFAnimationChannel[]; samplers: GLTFAnimationSampler[]; duration: number }

export interface GLTFCamera {
  name: string;
  type: 'perspective' | 'orthographic';
  perspective?: { yfov: number; znear: number; zfar?: number; aspectRatio?: number };
  orthographic?: { xmag: number; ymag: number; znear: number; zfar: number };
}

/** Added: undecoded image payload (always populated, also in environments without createImageBitmap). */
export interface GLTFImageData {
  name: string;
  mimeType: string;
  /** Encoded bytes (PNG/JPEG/WebP...). */
  data: Uint8Array;
}

export interface GLTFAsset {
  meshes: GLTFMesh[];
  materials: GLTFMaterial[];
  /**
   * Decoded images (index = glTF image index). Empty when `createImageBitmap` is unavailable
   * (e.g. Node) or image decoding was disabled — see `imageData` for the raw bytes.
   */
  images: ImageBitmap[];
  nodes: GLTFNode[];
  scenes: { name: string; nodes: number[] }[];
  scene: number;
  skins: GLTFSkin[];
  animations: GLTFAnimation[];
  extensionsUsed: string[];
  // ---- added
  imageData: GLTFImageData[];
  cameras: GLTFCamera[];
  lights: GLTFLight[];
  extensionsRequired: string[];
}

// ---------------------------------------------------------------- raw JSON (subset)

export type JSONObject = Record<string, unknown>;

export interface RawAccessorSparse {
  count: number;
  indices: { bufferView: number; byteOffset?: number; componentType: number };
  values: { bufferView: number; byteOffset?: number };
}
export interface RawAccessor {
  bufferView?: number; byteOffset?: number; componentType: number; normalized?: boolean;
  count: number; type: string; max?: number[]; min?: number[]; sparse?: RawAccessorSparse; name?: string;
}
export interface RawBufferView { buffer: number; byteOffset?: number; byteLength: number; byteStride?: number; target?: number; extensions?: JSONObject }
export interface RawBuffer { uri?: string; byteLength: number; extensions?: JSONObject }
export interface RawTextureInfo { index: number; texCoord?: number; scale?: number; strength?: number; extensions?: JSONObject }
export interface RawMaterial {
  name?: string;
  pbrMetallicRoughness?: {
    baseColorFactor?: number[]; baseColorTexture?: RawTextureInfo;
    metallicFactor?: number; roughnessFactor?: number; metallicRoughnessTexture?: RawTextureInfo;
  };
  normalTexture?: RawTextureInfo; occlusionTexture?: RawTextureInfo; emissiveTexture?: RawTextureInfo;
  emissiveFactor?: number[]; alphaMode?: string; alphaCutoff?: number; doubleSided?: boolean;
  extensions?: JSONObject;
}
export interface RawPrimitive {
  attributes: Record<string, number>; indices?: number; material?: number; mode?: number;
  targets?: Record<string, number>[]; extensions?: JSONObject;
}
export interface RawMesh { name?: string; primitives: RawPrimitive[]; weights?: number[] }
export interface RawNode {
  name?: string; children?: number[]; mesh?: number; skin?: number; camera?: number;
  matrix?: number[]; translation?: number[]; rotation?: number[]; scale?: number[]; weights?: number[];
  extensions?: JSONObject;
}
export interface RawSkin { name?: string; joints: number[]; inverseBindMatrices?: number; skeleton?: number }
export interface RawAnimation {
  name?: string;
  channels: { sampler: number; target: { node?: number; path: string } }[];
  samplers: { input: number; output: number; interpolation?: string }[];
}
export interface RawImage { uri?: string; mimeType?: string; bufferView?: number; name?: string }
export interface RawTexture { sampler?: number; source?: number; extensions?: JSONObject }
export interface RawSampler { magFilter?: number; minFilter?: number; wrapS?: number; wrapT?: number }
export interface RawCamera {
  name?: string; type: string;
  perspective?: { yfov: number; znear: number; zfar?: number; aspectRatio?: number };
  orthographic?: { xmag: number; ymag: number; znear: number; zfar: number };
}

export interface RawGLTF {
  asset: { version: string; minVersion?: string; generator?: string };
  accessors?: RawAccessor[]; bufferViews?: RawBufferView[]; buffers?: RawBuffer[];
  materials?: RawMaterial[]; meshes?: RawMesh[]; nodes?: RawNode[];
  scenes?: { name?: string; nodes?: number[] }[]; scene?: number;
  skins?: RawSkin[]; animations?: RawAnimation[]; images?: RawImage[]; textures?: RawTexture[]; samplers?: RawSampler[];
  cameras?: RawCamera[];
  extensionsUsed?: string[]; extensionsRequired?: string[]; extensions?: JSONObject;
}

